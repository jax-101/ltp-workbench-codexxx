const assert = require("node:assert/strict");
const fs = require("node:fs/promises");
const path = require("node:path");
const { compileDefinition, loadDefinition } = require("../src/core/definition-runtime");

const root = path.join(__dirname, "..");
const outputPath = path.join(root, "src", "generated", "official-diagram-registry.js");
const packageNames = ["goal-tree", "crt", "ec"];
const supportedCapabilities = ["semantic.graph.v1"];

async function buildRegistry() {
  const compiled = [];
  for (const name of packageNames) {
    const definitionPackage = await loadDefinition({
      kind: "directory",
      rootPath: path.join(root, "diagram-definitions", "official", name)
    }, { supportedCapabilities });
    compiled.push(compileDefinition(definitionPackage));
  }
  return {
    definitions: Object.fromEntries(compiled.map((item) => [item.runtimeId, item.registryDefinition])),
    semanticProfiles: Object.fromEntries(compiled.map((item) => [item.semanticDiagramType, item.semanticProfile])),
    pins: Object.fromEntries(compiled.map((item) => [item.runtimeId, item.pin]))
  };
}

function renderRegistry(registry) {
  const json = JSON.stringify(registry, null, 2);
  return `// Generated by scripts/build-official-definition-registry.js. Do not edit.\n` +
`(function exposeOfficialDefinitions(root, factory) {\n` +
`  const registry = factory();\n` +
`  if (typeof module !== "undefined" && module.exports) module.exports = registry;\n` +
`  if (root) root.LTP_OFFICIAL_DIAGRAM_REGISTRY = registry;\n` +
`})(typeof globalThis !== "undefined" ? globalThis : this, function createRegistry() {\n` +
`  const value = ${json};\n` +
`  const freeze = (item) => {\n` +
`    if (!item || typeof item !== "object" || Object.isFrozen(item)) return item;\n` +
`    Object.values(item).forEach(freeze);\n` +
`    return Object.freeze(item);\n` +
`  };\n` +
`  return freeze(value);\n` +
`});\n`;
}

async function main() {
  const expected = renderRegistry(await buildRegistry());
  if (process.argv.includes("--check")) {
    const actual = await fs.readFile(outputPath, "utf8");
    assert.equal(actual, expected, "Generated official definition registry is stale");
    console.log("Official definition registry is current.");
    return;
  }
  await fs.writeFile(outputPath, expected, "utf8");
  console.log(`Generated ${path.relative(root, outputPath)} from ${packageNames.length} secure packages.`);
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
